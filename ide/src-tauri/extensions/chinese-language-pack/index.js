export function activate(ide) {
  ide.locale.registerLocale("zh-CN", ZH_CN);
  ide.locale.setLocale("zh-CN");

  ide.commands.register("locale.switchToChinese", () => {
    ide.locale.setLocale("zh-CN");
    ide.window.showInformationMessage("已切换为简体中文");
  });

  ide.commands.register("locale.switchToEnglish", () => {
    ide.locale.setLocale("en");
    ide.window.showInformationMessage("Switched to English");
  });
}

export function deactivate() {}
