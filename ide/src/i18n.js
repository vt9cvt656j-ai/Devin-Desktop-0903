let currentLocale = "zh-CN";
let translations = { en: EN, "zh-CN": ZH_CN };
let changeListeners = [];

export function t(key, params) {
  const dict = translations[currentLocale] || translations.en;
  let str = dict[key] ?? EN[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, v);
    }
  }
  return str;
}

export function registerLocale(locale, dict) {
  translations[locale] = { ...EN, ...dict };
}

export function setLocale(locale) {
  if (!translations[locale]) return;
  currentLocale = locale;
  localStorage.setItem("michael-ide-locale", locale);
  applyToDOM();
  for (const fn of changeListeners) {
    try { fn(locale); } catch { /* ignore */ }
  }
}

export function getLocale() {
  return currentLocale;
}

export function onLocaleChange(fn) {
  changeListeners.push(fn);
  return () => {
    changeListeners = changeListeners.filter((f) => f !== fn);
  };
}

export function applyToDOM() {
  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  }
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.placeholder = t(key);
  }
  for (const el of document.querySelectorAll("[data-i18n-title]")) {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.title = t(key);
  }
  for (const el of document.querySelectorAll("[data-i18n-aria-label]")) {
    const key = el.getAttribute("data-i18n-aria-label");
    if (key) el.setAttribute("aria-label", t(key));
  }
}

export function initLocale() {
  const saved = localStorage.getItem("michael-ide-locale");
  if (saved && translations[saved]) {
    currentLocale = saved;
  } else {
    currentLocale = "zh-CN";
  }
  applyToDOM();
}
