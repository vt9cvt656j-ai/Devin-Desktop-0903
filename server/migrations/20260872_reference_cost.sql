-- 「这一笔到底花了我们多少」——和售价分开记。
--
-- `model_usage.cost_cents` 记的是**售价**。售价可以是 0（运营决定某个模型免费），
-- 成本却不是 0。于是所有成本报表都说这些模型不花钱：实测 deepseek-v4-pro 三天
-- 2954 次调用、1.36 亿 token，cost_cents 全是 0，而同一批 token 按实时目录价值 $228。
-- 对账页「成本侧只覆盖 26.8% 的流量」「每一行毛利都是负的」都有这一条的份。
--
-- 这一列由 `models.rs::reference_micro_usd` 在收到回执时算出来，走的是和计费
-- **同一份** token 解析（`priced_usd`），只是把价目强制换成实时目录、不乘线路倍率。
--
-- **可空，而且 NULL 不是 0。** NULL = 实时目录里没有这个模型的价（实验模型、自建
-- 模型、刚上的新模型）。报表必须能区分「不花钱」和「不知道花了多少」——把两者压成
-- 0 正是今天这张表的毛病，压完之后毛利率看起来还特别好。
--
-- 单位是 micro-USD 不是分：一次 glm-5.3-flash 调用只值 $0.003，按分存会全是 0，
-- 而那恰好是需要看清楚的那一档。
ALTER TABLE model_usage ADD COLUMN IF NOT EXISTS ref_micro_usd bigint;
